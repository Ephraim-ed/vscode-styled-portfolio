import { Workbench } from "@/components/workbench/workbench";
import { education, experience, profile } from "@/data/profile";
import { highlightWorkspace } from "@/lib/highlight";
import { siteUrl } from "@/lib/site";

export default async function Page() {
  const { files, css } = await highlightWorkspace();

  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Person",
    name: profile.name,
    jobTitle: profile.role,
    email: `mailto:${profile.email}`,
    url: siteUrl,
    address: {
      "@type": "PostalAddress",
      addressLocality: profile.address.locality,
      addressRegion: profile.address.region,
      addressCountry: profile.address.country,
    },
    worksFor: { "@type": "Organization", name: experience[0].company },
    alumniOf: { "@type": "CollegeOrUniversity", name: education.school },
    knowsAbout: profile.coreStack,
    sameAs: [profile.links.github, profile.links.linkedin, ...(profile.links.extra ? [profile.links.extra.url] : [])],
  };

  return (
    <>
      {/* Token colors for every theme, generated by Shiki at build time. */}
      <style dangerouslySetInnerHTML={{ __html: css }} />
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd).replace(/</g, "\\u003c") }}
      />
      <Workbench files={files} />
    </>
  );
}
