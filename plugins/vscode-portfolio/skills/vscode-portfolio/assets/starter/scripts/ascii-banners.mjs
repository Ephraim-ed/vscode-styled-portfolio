#!/usr/bin/env node
/**
 * Generates the FIGlet lettering used on the site (FIGlet is the text-banner route the ascii-art
 * agent skill recommends):
 *   - src/data/greeting.ts    "Hi, I am / <first name>" + a waving hand, top of README.md,
 *     in DOS Rebel: solid █ letters shaded with a ░ drop shadow (the site renders the art in a
 *     system monospace font that has these block glyphs, so it stays aligned), and the intro the
 *     preview plays before it: "Good morning!" (or afternoon, or evening), "Welcome to my workspace"
 *   - src/data/assistant-banner.ts  "<assistant name> / <title>" on the chat's start page, in Slant
 *   - src/data/monogram-art.ts  the monogram ("AR") beside `neofetch` in the terminal, in Standard
 *
 * Words are stacked one per block so the letters stay large in narrow columns.
 *
 * Usage: npm run banners
 */
import { writeFileSync } from "node:fs";
import figlet from "figlet";

import { assistant, profile } from "../src/data/profile.ts";

const GREETING_FONT = "DOS Rebel";
const BANNER_FONT = "Slant";
const MONOGRAM_FONT = "Standard";

/** Renders each part with FIGlet and stacks them, trimming blank edges. */
function letter(parts, font) {
  return parts.flatMap((part) => {
    const lines = figlet.textSync(part, { font }).split("\n").map((l) => l.replace(/\s+$/, ""));
    while (lines.length && !lines[0].trim()) lines.shift();
    while (lines.length && !lines.at(-1).trim()) lines.pop();
    return lines;
  });
}

// A raised hand to sit beside the last word: drawn solid, then shaded like the letters. The
// README preview animates it waving; the raw file keeps it static.
const HAND_SOLID = [
  "   ██ ██",
  "██ ██ ██ ██",
  "██ ██ ██ ██",
  "██ ██ ██ ██ ██",
  "███████████ ██",
  "█████████████",
  "████████████",
  " ██████████",
  "  ████████",
];

/** DOS Rebel's shading: every █ casts a ░ one row down and one column left, wherever that's empty. */
function shade(solid) {
  const width = Math.max(...solid.map((r) => r.length)) + 1;
  const at = (y, x) => solid[y]?.[x] === "█";
  return Array.from({ length: solid.length + 1 }, (_, y) =>
    Array.from({ length: width }, (_, x) => (at(y, x - 1) ? "█" : at(y - 1, x) ? "░" : " "))
      .join("")
      .replace(/\s+$/, ""),
  );
}

const HAND = shade(HAND_SOLID);

const widthOf = (lines) => Math.max(...lines.map((l) => l.length));

/** Whether `art` fits at column `col` with its bottom on row `bottom`, covering only blank cells. */
function fits(lines, art, col, bottom = lines.length) {
  const row = bottom - art.length;
  return lines.every((l, i) => i < row || i >= bottom || !l.slice(col, col + art[i - row].length).trim());
}

/** Places `art` at column `col` with its bottom on row `bottom` (the last row, unless said); it may
 * only cover blank cells. */
function place(lines, art, col, bottom = lines.length) {
  const row = bottom - art.length;
  if (!fits(lines, art, col, bottom)) throw new Error("the hand would overlap the lettering");
  const out = lines.map((l, i) => {
    if (i < row || i >= bottom) return l;
    const piece = art[i - row];
    return (l.padEnd(col).slice(0, col) + piece + l.slice(col + piece.length)).replace(/\s+$/, "");
  });
  return { lines: out, at: { row, col, lines: art } };
}

function write(path, exportName, font, lines, label, extra = "") {
  if (lines.some((l) => l.includes("```"))) throw new Error(`${path}: lettering would close a markdown fence`);
  writeFileSync(
    path,
    `// Generated by scripts/ascii-banners.mjs (FIGlet, font: ${font}) — do not edit by hand.\n` +
      `export const ${exportName}Label = ${JSON.stringify(label)};\n` +
      `export const ${exportName}: string[] = ${JSON.stringify(lines, null, 2)};\n` +
      extra,
  );
  console.log(`Wrote ${path} (${Math.max(...lines.map((l) => l.length))}x${lines.length})`);
}

const nickname = profile.firstName;

// Two lines, each centred: "Hi, I am", then the first name with the hand beside it, standing on the
// name's baseline (below it hang only the descenders, like the p's).
const upper = [letter(["Hi, I am"], GREETING_FONT)];
const last = letter([nickname], GREETING_FONT);
const lastWidth = widthOf(last) + 2 + widthOf(HAND);
const artWidth = Math.max(...upper.map(widthOf), lastWidth);
const centred = (block, width) => block.map((l) => " ".repeat(Math.floor((artWidth - width) / 2)) + l);
const above = upper.flatMap((block) => centred(block, widthOf(block)));
// The hand is taller than the name's capitals: with a short name it would reach up into "Hi, I am",
// so the two lines move apart until it clears.
const handCol = Math.floor((artWidth - lastWidth) / 2) + widthOf(last) + 2;
const handBottom = (gap) => above.length + gap + letter(["E"], GREETING_FONT).length;
let gap = 0;
while (!fits([...above, ...Array(gap).fill(""), ...centred(last, lastWidth)], HAND, handCol, handBottom(gap))) gap++;
const art = place([...above, ...Array(gap).fill(""), ...centred(last, lastWidth)], HAND, handCol, handBottom(gap));

// The intro the README preview plays before the greeting, one phrase after another. It opens by the
// visitor's time of day: the preview picks one of OPENERS when it plays. ("Good afternoon!" is split
// so the widest phrase, and so the canvas, stays "my workspace".)
const OPENERS = {
  morning: ["Good morning!"],
  afternoon: ["Good", "afternoon!"],
  evening: ["Good evening!"],
};
const INTRO = [["Welcome to", "my workspace"]];

/** A phrase's lettering, its lines centred on each other. */
function block(parts) {
  const blocks = parts.map((part) => letter([part], GREETING_FONT));
  const width = Math.max(...blocks.map(widthOf));
  return blocks.flatMap((b) => b.map((l) => " ".repeat(Math.floor((width - widthOf(b)) / 2)) + l));
}

// Everything (the intro and the greeting) plays on one canvas, big enough for the widest and the
// tallest, each centred on it, so the lettering keeps its size and nothing shifts between them.
const pieces = [art.lines, ...INTRO.map(block), ...Object.values(OPENERS).map(block)];
const canvas = { cols: Math.max(...pieces.map(widthOf)), rows: Math.max(...pieces.map((p) => p.length)) };
const offset = (lines) => ({
  left: Math.floor((canvas.cols - widthOf(lines)) / 2),
  top: Math.floor((canvas.rows - lines.length) / 2),
});
function onCanvas(lines) {
  const { left, top } = offset(lines);
  return Array.from({ length: canvas.rows }, (_, i) =>
    (lines[i - top] ? " ".repeat(left) + lines[i - top] : "").replace(/\s+$/, ""),
  );
}
const scene = (parts) => ({ label: parts.join(" "), lines: onCanvas(block(parts)) });
const at = offset(art.lines);

write(
  "src/data/greeting.ts",
  "greeting",
  GREETING_FONT,
  onCanvas(art.lines),
  `Hi, I am ${nickname}`,
  `/** Where the waving hand sits in \`greeting\` (rows and columns), so the preview can animate it. */\n` +
    `export const greetingHand = ${JSON.stringify({ ...art.at, row: art.at.row + at.top, col: art.at.col + at.left }, null, 2)};\n` +
    `/** The canvas the greeting and its intro share, in characters. */\n` +
    `export const greetingCanvas = ${JSON.stringify(canvas)};\n` +
    `/** The intro played before the greeting (see Greeting), each phrase centred on the canvas. */\n` +
    `export const greetingIntro: { label: string; lines: string[] }[] = ${JSON.stringify(INTRO.map(scene), null, 2)};\n` +
    `/** The intro's first phrase, by the visitor's time of day. */\n` +
    `export const greetingOpeners: Record<"morning" | "afternoon" | "evening", { label: string; lines: string[] }> = ${JSON.stringify(
      Object.fromEntries(Object.entries(OPENERS).map(([when, parts]) => [when, scene(parts)])),
      null,
      2,
    )};\n`,
);
write(
  "src/data/assistant-banner.ts",
  "assistantBanner",
  BANNER_FONT,
  letter([assistant.name, assistant.title], BANNER_FONT),
  `${assistant.name} ${assistant.title}`,
);
write(
  "src/data/monogram-art.ts",
  "monogramArt",
  MONOGRAM_FONT,
  letter([profile.monogram.toUpperCase()], MONOGRAM_FONT),
  profile.monogram.toUpperCase(),
);
